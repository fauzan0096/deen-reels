_DIGITS = str.maketrans(
    "۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789"
)

_PUNCT = str.maketrans(
    {
        "۔": ".",
        "،": ",",
        "؛": ";",
        "؟": "?",
        "«": "",
        "»": "",
        "ﷺ": "",
    }
)


def _load_overrides() -> Dict[str, str]:
    if not OVERRIDES_PATH.exists():
        return {}
    try:
        data = json.loads(OVERRIDES_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    return {str(key): str(value) for key, value in (data.get("words") or {}).items()}


WORDS: Dict[str, str] = {**_WORDS_BUILTIN, **_load_overrides()}
# Lambe juz pehle, warna "ابو بکر" chhoti entry se toot jaye.
_SORTED = sorted(WORDS.items(), key=lambda kv: len(kv[0]), reverse=True)


def _pattern(word: str) -> re.Pattern:
    """Poore lafz par match — "عمر" ko "عمرو" ke andar na badle."""
    return re.compile(f"(?<!{URDU_LETTER}){re.escape(word)}(?!{URDU_LETTER})")


_PATTERNS = [(word, spoken, _pattern(word)) for word, spoken in _SORTED]


def _numbers(text: str) -> str:
    """0-99 ke adad Urdu lafzon me — Urdu voice "thirteen" na bole."""

    def replace(match: re.Match) -> str:
        value = int(match.group(0))
        return _NUMBERS.get(value, match.group(0))

    return re.sub(r"(?<!\d)\d{1,2}(?!\d)", replace, text)


def say(text: str) -> str:
    """Awaaz ke liye text: harakat wale lafz, Urdu adad, saaf punctuation."""
    if not text:
        return ""

    text = text.translate(_DIGITS)
    for word, spoken, pattern in _PATTERNS:
        if word in text:
            text = pattern.sub(spoken, text)

    text = _numbers(text)
    return text.translate(_PUNCT)

